#[test]
fn the_derived_readers_and_writers_share_the_grammar() {
    assert_eq!(parse_iso_millis("2024-01-02"), Some(1_704_153_600_000));
    assert_eq!(
        parse_iso_millis("2024-01-02T10:30:15,1239+01:00"),
        Some(1_704_187_815_123)
    );
    assert_eq!(parse_iso_millis("1969-12-31T23:59:59"), None);
    assert_eq!(
        normalize_iso_utc("2024-01-02T10:30:15.1234567+01:00").as_deref(),
        Some("2024-01-02T09:30:15.123456+00:00")
    );
    assert_eq!(
        format_iso_millis_z(1_704_187_815_123),
        "2024-01-02T09:30:15.123Z"
    );
    assert_eq!(format_iso_millis_z(0), "1970-01-01T00:00:00.000Z");
}
