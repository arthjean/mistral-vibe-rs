//! The two stamp grammars against what the pinned interpreter answers for the
//! same input, each instant written in UTC, a naive one read as UTC. The
//! expectations were measured with `datetime.fromisoformat` and a pydantic
//! `TypeAdapter(datetime)` under the reference's interpreter.

use super::{UtcTimestamp, format_iso_millis_z, normalize_iso_utc, parse_iso_millis};

fn check(parse: fn(&str) -> Option<UtcTimestamp>, cases: &[(&str, Option<&str>)]) {
    for (input, expected) in cases {
        let parsed = parse(input).map(UtcTimestamp::to_iso8601);
        assert_eq!(parsed.as_deref(), *expected, "{input:?}");
    }
}

